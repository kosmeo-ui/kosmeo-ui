type CamelCase<S extends string> = S extends `${infer Head}-${infer Tail}`
  ? `${Head}${Capitalize<CamelCase<Tail>>}`
  : S;

/** A theme token by camelCased name: `primaryColor` for `--k-primary-color`. */
export type ThemeToken = CamelCase<(typeof themeTokenNames)[number]>;
